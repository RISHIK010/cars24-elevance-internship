using MongoDB.Bson;
using MongoDB.Bson.Serialization.Attributes;

namespace Cars24API.Models;

public enum NotificationType
{
    AppointmentConfirmation,
    BidUpdate,
    PriceDrop,
    NewMessage
}

public enum NotificationChannel
{
    BrowserPush
}

public class NotificationPreferences
{
    public bool BrowserPush { get; set; } = true;
    public bool AppointmentConfirmations { get; set; } = true;
    public bool BidUpdates { get; set; } = true;
    public bool PriceDrops { get; set; } = true;
    public bool NewMessages { get; set; } = true;
}

public class NotificationDevice
{
    [BsonId]
    [BsonRepresentation(BsonType.ObjectId)]
    public string? Id { get; set; }

    public string UserId { get; set; } = string.Empty;

    /// <summary>Browser/device identifier generated by the client.</summary>
    public string DeviceId { get; set; } = string.Empty;

    /// <summary>Current FCM registration token (browser push target).</summary>
    public string RegistrationToken { get; set; } = string.Empty;

    public bool IsActive { get; set; } = true;

    public NotificationChannel Channel { get; set; } = NotificationChannel.BrowserPush;

    public NotificationPreferences Preferences { get; set; } = new();

    [BsonDateTimeOptions(Kind = DateTimeKind.Utc)]
    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;

    [BsonDateTimeOptions(Kind = DateTimeKind.Utc)]
    public DateTime UpdatedAtUtc { get; set; } = DateTime.UtcNow;
}
